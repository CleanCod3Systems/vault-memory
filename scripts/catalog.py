#!/usr/bin/env python3
"""vault-memory catalog — a generated page with one line per note: the front door of the vault.

Written by `refresh` when `catalog.path` is set. Each line is `- [[title]] — summary` (the
note's `description`, or the first sentence of its body), grouped by area or by folder and
sorted, so the same vault always gives the same text. It starts with a marker that says it is
generated: the indexer reads that marker to treat the page as an `index` that is never an
answer (not in recall, not in the bench, not a source of links).

Config `catalog` (all optional):
    path        null        vault-relative path of the page; null = off
    group_by    "area"      "area" or "folder" (the folder that contains the note)
    skip_types  [daily, period, home, index]   types left out of the page

It only writes when the text changed, and never over a page that was not generated.
"""
import re
from pathlib import Path

import core as C

DEFAULTS = {"path": None, "group_by": "area", "skip_types": ["daily", "period", "home", "index"]}
GENERATED = "<!-- vault-memory: generated"     # every page refresh writes starts with this
MARKER = "<!-- vault-memory: generated catalog. Do not edit by hand: `vault-memory refresh` rewrites it. -->"
SUMMARY_MAX = 140
SENTENCE = re.compile(r"(.+?[.!?])(?:\s|$)")


class CatalogError(Exception):
    pass


def options(cfg):
    return {**DEFAULTS, **(cfg.get("catalog") or {})}


def is_generated(text):
    """True if the page carries the marker right after its frontmatter."""
    return C.frontmatter(text)[1].lstrip().startswith(GENERATED)


def _target(cfg, opts):
    rel = str(opts["path"]).strip().replace("\\", "/")
    if not rel.endswith(".md"):
        rel += ".md"
    vault = Path(cfg["_vault"]).resolve()
    target = (vault / rel).resolve()
    if rel.startswith("/") or vault not in target.parents:
        raise CatalogError(f"catalog.path must be inside the vault: {opts['path']}")
    if C.under_captures(target):
        raise CatalogError(f"catalog.path cannot be inside the captures folder: {opts['path']}")
    return rel, target


def _one_line(text):
    return re.sub(r"\s+", " ", text).strip()


def summary(doc):
    text = _one_line(doc.get("desc") or "")
    if not text:
        snippet = _one_line(doc.get("s") or "")
        match = SENTENCE.match(snippet)
        text = match.group(1) if match else snippet
    if len(text) > SUMMARY_MAX:
        text = text[:SUMMARY_MAX - 1].rstrip() + "…"
    return text


def _label(text):
    """Alias text that cannot break a wikilink: no pipe, brackets or newlines."""
    return _one_line(re.sub(r"[\[\]]", "", text.replace("|", "/")))


def _link(doc, repeated):
    target = doc["p"][:-3] if doc["n"] in repeated else doc["n"]
    title = _label(doc["t"])
    return f"[[{target}]]" if title == target else f"[[{target}|{title}]]"


def _group(doc, group_by):
    if group_by == "folder":
        return doc["p"].rsplit("/", 1)[0] if "/" in doc["p"] else "(root)"
    return doc["area"] or "general"


def render(cfg, docs, rel):
    opts = options(cfg)
    group_by = opts["group_by"]
    if group_by not in ("area", "folder"):
        raise CatalogError(f"catalog.group_by must be 'area' or 'folder': {group_by}")
    skip = set(opts["skip_types"])
    notes = [d for d in docs if d["p"] != rel and not d["archived"] and not d.get("template")
             and not d.get("generated") and d["type"] not in skip]
    names = {}
    for d in notes:
        names[d["n"]] = names.get(d["n"], 0) + 1
    repeated = {n for n, count in names.items() if count > 1}
    groups = {}
    for d in notes:
        groups.setdefault(_group(d, group_by), []).append(d)

    lines = ["---", "type: index", f"area: {cfg.get('default_area', 'general')}", "tags:", "  - index", "---", "",
             MARKER, "", "# Catalog", "", f"{len(notes)} notes, grouped by {group_by}.", ""]
    for name in sorted(groups, key=lambda g: (g.casefold(), g)):
        lines += [f"## {name}", ""]
        for d in sorted(groups[name], key=lambda d: (d["t"].casefold(), d["p"])):
            text = summary(d)
            lines.append(f"- {_link(d, repeated)}" + (f" — {text}" if text else ""))
        lines.append("")
    return "\n".join(lines)


def write(cfg, docs):
    """The catalog's relative path if it was (re)written, None if off or unchanged."""
    opts = options(cfg)
    if not opts["path"]:
        return None
    rel, target = _target(cfg, opts)
    text = render(cfg, docs, rel)
    if target.exists():
        current = target.read_text(encoding="utf-8")
        if not is_generated(current):
            raise CatalogError(f"{rel} exists and was not generated by vault-memory: not overwritten")
        if current == text:
            return None
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return rel
